#!/usr/bin/env bash
# Generate the colour files that can include a palette and check the ones that
# cannot. The palette itself lives in palette.sh.
# Usage: apply.sh [generate|check]   (default: generate, then check)
#   generate: write sway/colors.conf, foot/colors.ini and the Taskwarrior theme
#   check:    fail if mako, swaylock or wofi use a colour outside the palette

set -eu
dir=$(dirname "$(readlink -f "$0")")
repo=$(dirname "$(dirname "$(dirname "$dir")")") # dir is <repo>/colors/.config/colors
. "$dir/palette.sh"

# pkgfile PKG/FILE: path of FILE inside the stow package PKG (PKG/.config/PKG/FILE)
pkgfile() { printf '%s/%s/.config/%s' "$repo" "${1%%/*}" "$1"; }

mapfile -t names < <(compgen -A variable C_ | sort)

# generate_sway: `set $c_name #hex` for every palette entry (included by sway/config)
generate_sway() {
  local n
  {
    printf '# Generated by colors/apply.sh from colors/palette.sh. Do not edit.\n'
    for n in "${names[@]}"; do printf 'set $%s #%s\n' "${n,,}" "${!n}"; done
  } >"$(pkgfile sway/colors.conf)"
}

# generate_foot: [colors] section (included by foot/foot.ini)
generate_foot() {
  local i
  local -a normal=(C_bg C_red C_green C_yellow C_blue C_purple C_aqua C_fg)
  local -a bright=(C_bg4 C_red_b C_green_b C_yellow_b C_blue_b C_purple_b C_aqua_b C_fg_b)
  {
    printf '# Generated by colors/apply.sh from colors/palette.sh. Do not edit.\n'
    printf '[colors]\nbackground=%s\nforeground=%s\n' "$C_bg" "$C_fg"
    for i in "${!normal[@]}"; do
      local nn=${normal[i]} bb=${bright[i]}
      printf 'regular%d=%s\nbright%d=%s\n' "$i" "${!nn}" "$i" "${!bb}"
    done
  } >"$(pkgfile foot/colors.ini)"
}

# to256 HEX: nearest xterm-256 colour index (6x6x6 cube or grey ramp).
# Taskwarrior only takes colorN / rgbRGB, so the palette is approximated.
to256() {
  local r=$((16#${1:0:2})) g=$((16#${1:2:2})) b=$((16#${1:4:2}))
  local -a lv=(0 95 135 175 215 255)
  local -a ix=() v=($r $g $b)
  local c i best d bd
  for c in 0 1 2; do
    bd=999999
    for i in 0 1 2 3 4 5; do
      d=$(((v[c] - lv[i]) ** 2))
      ((d < bd)) && { bd=$d; best=$i; }
    done
    ix[c]=$best
  done
  local cube=$((16 + 36 * ix[0] + 6 * ix[1] + ix[2]))
  local cd=$(((r - lv[ix[0]]) ** 2 + (g - lv[ix[1]]) ** 2 + (b - lv[ix[2]]) ** 2))
  local avg=$(((r + g + b) / 3))
  local gi=$(((avg - 8 + 5) / 10))
  ((gi < 0)) && gi=0
  ((gi > 23)) && gi=23
  local gv=$((8 + 10 * gi))
  local gd=$(((r - gv) ** 2 + (g - gv) ** 2 + (b - gv) ** 2))
  if ((gd < cd)); then echo $((232 + gi)); else echo $cube; fi
}

# idx256 NAME: 256-colour index for palette entry NAME. The nearest match is wrong
# for two entries (blue collides with aqua, grey turns pink), so they are fixed.
idx256() {
  case $1 in
  C_blue_b) echo 109 ;;
  C_gray) echo 245 ;;
  *) to256 "${!1}" ;;
  esac
}

# generate_task: Taskwarrior and taskwarrior-tui theme (included by ~/.taskrc)
generate_task() {
  local out=$repo/taskwarrior/.config/task/gruvbox.theme
  local bg fg gray dim bg1 bg2 red green yellow blue purple aqua orange
  bg=color$(idx256 C_bg); fg=color$(idx256 C_fg); gray=color$(idx256 C_gray)
  dim=color$(idx256 C_bg4); bg1=color$(idx256 C_bg1); bg2=color$(idx256 C_bg2)
  red=color$(idx256 C_red_b); green=color$(idx256 C_green_b); yellow=color$(idx256 C_yellow_b)
  blue=color$(idx256 C_blue_b); purple=color$(idx256 C_purple_b); aqua=color$(idx256 C_aqua_b)
  orange=color$(idx256 C_orange_b)
  # Project and tag colours: edit these lists to match your own
  local -A proj=([dots]=$aqua [work]=$blue [home]=$green)
  local -A tag=([work]=$blue [home]=$green [waiting]=$dim)
  local k
  {
    printf '# Generated by colors/apply.sh from colors/palette.sh. Do not edit.\n'
    cat <<EOF
rule.precedence.color=deleted,completed,active,overdue,due.today,keyword.,tag.,project.,scheduled,due,blocked,blocking,recurring,tagged,uda.

color.active=$bg on $green
color.alternate=
color.blocked=$gray
color.blocking=$orange
color.burndown.done=$bg on $green
color.burndown.pending=$bg on $red
color.burndown.started=$bg on $yellow
color.calendar.due=$bg on $yellow
color.calendar.due.today=$bg on $orange
color.calendar.holiday=$bg on $purple
color.calendar.overdue=$bg on $red
color.calendar.scheduled=$bg on $blue
color.calendar.today=$bg on $orange
color.calendar.weekend=$gray on $bg1
color.calendar.weeknumber=$yellow
color.completed=$gray
color.debug=$purple
color.deleted=$dim
color.error=$bg on $red
color.footnote=$aqua
color.header=$yellow
color.history.add=$bg on $red
color.history.delete=$bg on $yellow
color.history.done=$bg on $green
color.label=$fg
color.label.sort=$fg underline
color.overdue=bold $red
color.project.none=
color.recurring=$blue
color.scheduled=$aqua
color.summary.background=on $bg1
color.summary.bar=$bg on $green
color.sync.added=$green
color.sync.changed=$yellow
color.sync.rejected=$red
color.tag.next=bold $yellow
color.tag.none=
color.tagged=$aqua
color.uda.priority.H=bold $red
color.uda.priority.M=$yellow
color.uda.priority.L=$blue
color.due=$yellow
color.due.today=bold $orange
color.warning=$bg on $yellow

# taskwarrior-tui: selected row with a visible background, accent on the chrome
uda.taskwarrior-tui.style.report.selection=bold $yellow on $bg2
uda.taskwarrior-tui.style.report.scrollbar=$yellow
uda.taskwarrior-tui.style.report.scrollbar.area=$bg2
uda.taskwarrior-tui.style.context.active=$bg on $yellow
uda.taskwarrior-tui.style.context.inactive=$gray on $bg1
uda.taskwarrior-tui.style.calendar.title=$yellow
uda.taskwarrior-tui.style.calendar.today=$bg on $orange

EOF
    for k in "${!proj[@]}"; do printf 'color.project.%s=%s\n' "$k" "${proj[$k]}"; done | sort
    for k in "${!tag[@]}"; do printf 'color.tag.%s=%s\n' "$k" "${tag[$k]}"; done | sort
  } >"$out"
}

# check: every colour in the hand-written files must be in the palette
check() {
  local -A known=()
  local n c f bad=0
  for n in "${names[@]}"; do known[${!n}]=1; done
  for f in mako/config wofi/style.css; do
    while read -r c; do
      [[ -n ${known[${c#\#}]:-} ]] || { printf '%s: #%s is not in the palette\n' "$f" "${c#\#}"; bad=1; }
    done < <(grep -ohiE '#[0-9a-f]{6}\b' "$(pkgfile "$f")" | tr 'A-F' 'a-f')
  done
  # swaylock writes colours without '#', optionally followed by 2 alpha digits
  while read -r c; do
    [[ -n ${known[${c:0:6}]:-} ]] || { printf 'swaylock/config: %s is not in the palette\n' "${c:0:6}"; bad=1; }
  done < <(sed -nE 's/^[a-z-]*color=([0-9a-fA-F]{6,8})$/\1/p' "$(pkgfile swaylock/config)" | tr 'A-F' 'a-f')
  return $bad
}

case ${1:-all} in
generate) generate_sway; generate_foot; generate_task ;;
check) check ;;
all) generate_sway; generate_foot; generate_task; check ;;
*) echo "usage: ${0##*/} [generate|check]" >&2; exit 1 ;;
esac
