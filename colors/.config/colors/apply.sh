#!/usr/bin/env bash
# Generate the colour files that can include a palette and check the ones that
# cannot. The palette itself lives in palette.sh.
# Usage: apply.sh [generate|check]   (default: generate, then check)
#   generate: write sway/colors.conf and foot/colors.ini
#   check:    fail if mako, swaylock or wofi use a colour outside the palette

set -eu
dir=$(dirname "$(readlink -f "$0")")
cfg=$(dirname "$dir")
. "$dir/palette.sh"

mapfile -t names < <(compgen -A variable C_ | sort)

# generate_sway: `set $c_name #hex` for every palette entry (included by sway/config)
generate_sway() {
  local n
  {
    printf '# Generated by colors/apply.sh from colors/palette.sh. Do not edit.\n'
    for n in "${names[@]}"; do printf 'set $%s #%s\n' "${n,,}" "${!n}"; done
  } >"$cfg/sway/colors.conf"
}

# generate_foot: [colors] section (included by foot/foot.ini)
generate_foot() {
  local i
  local -a normal=(C_bg C_red C_green C_yellow C_blue C_purple C_aqua C_fg)
  local -a bright=(C_bg4 C_red_b C_green_b C_yellow_b C_blue_b C_purple_b C_aqua_b C_fg_b)
  {
    printf '# Generated by colors/apply.sh from colors/palette.sh. Do not edit.\n'
    printf '[colors]\nbackground=%s\nforeground=%s\n' "$C_bg" "$C_fg"
    for i in "${!normal[@]}"; do
      local nn=${normal[i]} bb=${bright[i]}
      printf 'regular%d=%s\nbright%d=%s\n' "$i" "${!nn}" "$i" "${!bb}"
    done
  } >"$cfg/foot/colors.ini"
}

# check: every colour in the hand-written files must be in the palette
check() {
  local -A known=()
  local n c f bad=0
  for n in "${names[@]}"; do known[${!n}]=1; done
  for f in mako/config wofi/style.css; do
    while read -r c; do
      [[ -n ${known[${c#\#}],,} ]] || { printf '%s: #%s is not in the palette\n' "$f" "${c#\#}"; bad=1; }
    done < <(grep -ohiE '#[0-9a-f]{6}\b' "$cfg/$f" | tr 'A-F' 'a-f')
  done
  # swaylock writes colours without '#', optionally followed by 2 alpha digits
  while read -r c; do
    [[ -n ${known[${c:0:6}]:-} ]] || { printf 'swaylock/config: %s is not in the palette\n' "${c:0:6}"; bad=1; }
  done < <(sed -nE 's/^[a-z-]*color=([0-9a-fA-F]{6,8})$/\1/p' "$cfg/swaylock/config" | tr 'A-F' 'a-f')
  return $bad
}

case ${1:-all} in
generate) generate_sway; generate_foot ;;
check) check ;;
all) generate_sway; generate_foot; check ;;
*) echo "usage: ${0##*/} [generate|check]" >&2; exit 1 ;;
esac
